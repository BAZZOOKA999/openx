package com.example.openx.engine.androidres

import com.example.openx.data.db.entities.BlockType
import com.example.openx.data.db.entities.TranslationStatus
import com.example.openx.data.db.entities.TranslationUnitEntity
import org.json.JSONObject

object AndroidResParser {

    private val XML_STRING_REGEX = Regex("<string\\s+name=\"([^\"]+)\"[^>]*>([\\s\\S]*?)</string>")

    data class ParsedResItem(
        val orderIndex: Int,
        val lineIndex: Int,
        val key: String,
        val originalText: String,
        val translatedText: String,
        val blockType: BlockType
    )

    fun parseStringsXml(content: String): List<ParsedResItem> {
        val items = mutableListOf<ParsedResItem>()
        var order = 0

        val matches = XML_STRING_REGEX.findAll(content)
        for (m in matches) {
            val key = m.groupValues[1]
            val rawValue = m.groupValues[2]
            val cleanValue = unescapeXml(rawValue)

            items.add(
                ParsedResItem(
                    orderIndex = order++,
                    lineIndex = 0,
                    key = key,
                    originalText = cleanValue,
                    translatedText = "",
                    blockType = BlockType.XML_STRING
                )
            )
        }
        return items
    }

    fun parseJson(content: String): List<ParsedResItem> {
        val items = mutableListOf<ParsedResItem>()
        var order = 0
        try {
            val jsonObj = JSONObject(content)
            val keys = jsonObj.keys()
            while (keys.hasNext()) {
                val key = keys.next()
                val value = jsonObj.optString(key, "")
                items.add(
                    ParsedResItem(
                        orderIndex = order++,
                        lineIndex = 0,
                        key = key,
                        originalText = value,
                        translatedText = "",
                        blockType = BlockType.JSON_KEY
                    )
                )
            }
        } catch (_: Exception) {
            // If flat line parsing needed
        }
        return items
    }

    fun parseCsv(content: String): List<ParsedResItem> {
        val items = mutableListOf<ParsedResItem>()
        var order = 0
        val lines = content.lines()
        for ((idx, line) in lines.withIndex()) {
            if (line.isBlank()) continue
            val parts = line.split(",", ";", "\t", limit = 2)
            if (parts.size >= 2) {
                items.add(
                    ParsedResItem(
                        orderIndex = order++,
                        lineIndex = idx + 1,
                        key = parts[0].trim().removeSurrounding("\""),
                        originalText = parts[1].trim().removeSurrounding("\""),
                        translatedText = "",
                        blockType = BlockType.CSV_CELL
                    )
                )
            } else {
                items.add(
                    ParsedResItem(
                        orderIndex = order++,
                        lineIndex = idx + 1,
                        key = "line_${idx + 1}",
                        originalText = line.trim(),
                        translatedText = "",
                        blockType = BlockType.GENERIC
                    )
                )
            }
        }
        return items
    }

    fun exportStringsXml(units: List<TranslationUnitEntity>): String {
        val sb = StringBuilder()
        sb.append("<?xml version=\"1.0\" encoding=\"utf-8\"?>\n")
        sb.append("<!-- Generated by OpenX Translation Suite -->\n")
        sb.append("<resources>\n")

        for (unit in units) {
            val value = if (unit.translatedText.isNotBlank()) unit.translatedText else unit.originalText
            val escaped = escapeXml(value)
            sb.append("    <string name=\"${unit.keyOrContext}\">$escaped</string>\n")
        }

        sb.append("</resources>\n")
        return sb.toString()
    }

    fun exportJson(units: List<TranslationUnitEntity>): String {
        val jsonObj = JSONObject()
        for (unit in units) {
            val value = if (unit.translatedText.isNotBlank()) unit.translatedText else unit.originalText
            jsonObj.put(unit.keyOrContext, value)
        }
        return jsonObj.toString(4)
    }

    private fun unescapeXml(text: String): String {
        return text.replace("&lt;", "<")
            .replace("&gt;", ">")
            .replace("&amp;", "&")
            .replace("&apos;", "'")
            .replace("&quot;", "\"")
            .replace("\\'", "'")
            .replace("\\\"", "\"")
            .replace("\\n", "\n")
            .trim()
    }

    private fun escapeXml(text: String): String {
        return text.replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("\"", "\\\"")
            .replace("'", "\\'")
    }
}
